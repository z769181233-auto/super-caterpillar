  router.post(
    '/api/projects/:projectId/import-jobs',
    async (req: Request<{ projectId: string }, unknown, CreateImportJobInput>, res) => {
      const record = await getProjectOr404(req.params.projectId, res);
      if (!record) {
        return;
      }

      if (!req.body?.fileId?.trim() || !req.body?.title?.trim()) {
        res.status(400).json({ message: 'fileId and title are required' });
        return;
      }

      const file = record.storedFiles.find((item) => item.id === req.body.fileId);
      if (!file) {
        res.status(400).json({ message: 'source file not found' });
        return;
      }

      const initialTitle =
        isWeakTitle(req.body.title) && !isSuspiciousStoredFilename(file.name) ? deriveTitleFromStoredFilename(file.name) || req.body.title : req.body.title;
      const job = createImportJob(record.project.id, { ...req.body, title: initialTitle });
      record.importJobs = record.importJobs.concat(job);
      appendVersion(record, {
        stage: record.project.stage,
        action: 'import_job_created',
        summary: `创建导入任务「${job.title}」`,
        detail: `已从文件「${file.name}」创建导入任务。`,
        metadata: {
          fileId: file.id
        }
      });

      try {
        markImportJobRunning(job);
        const text = readStoredTextFile(file);
        const inferredTitle = inferNovelTitleFromText(text, file.name);
        const resolvedTitle = isWeakTitle(job.title) && inferredTitle ? inferredTitle : job.title;
        job.title = resolvedTitle;
        if (inferredTitle && isSuspiciousStoredFilename(file.name)) {
          file.name = recoverStoredFilename(file.name, inferredTitle);
        }
        const result = importNovel(record.project.id, {
          title: resolvedTitle,
          author: job.author,
          text
        });

        record.novel = result.novel;
        record.characters = result.characters;
        clearImportState(record, { keepAssets: true, keepStoredFiles: true });
        record.importJobs = record.importJobs.filter((item) => item.id !== job.id).concat(job);
        markImportJobCompleted(job, result.novel);
        record.project.stage = 'novel_imported';
        record.project.updatedAt = now();
        appendVersion(record, {
          stage: record.project.stage,
          action: 'import_job_completed',
          summary: `导入任务完成「${job.title}」`,
          detail: `已完成源文件导入，累计 ${result.novel.wordCount} 字，并切分 ${result.novel.chapterCount} 章。`,
          metadata: {
            wordCount: result.novel.wordCount,
            chapterCount: result.novel.chapterCount
          }
        });
        appendVersion(record, {
          stage: record.project.stage,
          action: 'novel_imported',
          summary: `导入小说《${result.novel.title}》`,
          detail: `完成原著导入，共切分 ${result.novel.chapterCount} 章，抽取 ${result.characters.length} 个核心角色。`,
          metadata: {
            chapterCount: result.novel.chapterCount,
            characterCount: result.characters.length,
            wordCount: result.novel.wordCount
          }
        });
        applyBaselineEpisodePackage(record);
      } catch (error) {
        markImportJobFailed(job, error instanceof Error ? error.message : 'unknown error');
      }

      await projectRepository.save(record);
      res.status(201).json(job);
    }
  );

