  router.post(
    '/api/projects/:projectId/files/upload',
    raw({ type: '*/*', limit: uploadBodyLimit }),
    async (req: Request<{ projectId: string }, unknown, Buffer>, res) => {
      const record = await getProjectOr404(req.params.projectId, res);
      if (!record) {
        return;
      }

      const name = typeof req.query.name === 'string' ? req.query.name.trim() : '';
      const kind = typeof req.query.kind === 'string' ? req.query.kind.trim() : '';
      const mimeTypeFromQuery = typeof req.query.mimeType === 'string' ? req.query.mimeType.trim() : '';
      const mimeType = mimeTypeFromQuery || req.header('content-type')?.trim() || 'application/octet-stream';
      const buffer = Buffer.isBuffer(req.body) ? req.body : Buffer.alloc(0);

      if (!name || !kind || !mimeType || buffer.byteLength === 0) {
        res.status(400).json({ message: 'name, kind, mimeType and binary body are required' });
        return;
      }

      if (kind !== 'novel_source' && kind !== 'asset_attachment') {
        res.status(400).json({ message: 'kind must be novel_source or asset_attachment' });
        return;
      }

      const file = storeProjectFileBuffer(record.project.id, {
        name,
        kind,
        mimeType,
        buffer
      });

      record.storedFiles = record.storedFiles.concat(file);
      record.project.updatedAt = now();
      appendVersion(record, {
        stage: record.project.stage,
        action: 'source_file_uploaded',
        summary: `上传源文件「${file.name}」`,
        detail: `已存储 ${file.kind} 文件，大小 ${file.byteSize} 字节。`,
        metadata: {
          byteSize: file.byteSize,
          kind: file.kind
        }
      });
      await projectRepository.save(record);

      res.status(201).json(file);
    }
  );

