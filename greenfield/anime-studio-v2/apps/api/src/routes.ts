  router.post(
    '/api/upload-sessions/:uploadSessionId/chunks',
    async (req: Request<{ uploadSessionId: string }, unknown, UploadChunkInput>, res) => {
      const snapshots = await projectRepository.list();
      const projectRecords = await Promise.all(snapshots.map((snapshot) => projectRepository.get(snapshot.project.id)));
      const record = projectRecords.find((item) => item?.uploadSessions.some((session) => session.id === req.params.uploadSessionId));

      if (!record) {
        res.status(404).json({ message: 'Upload session not found' });
        return;
      }

      const session = record.uploadSessions.find((item) => item.id === req.params.uploadSessionId);
      if (!session) {
        res.status(404).json({ message: 'Upload session not found' });
        return;
      }

      if (session.status !== 'receiving') {
        res.status(400).json({ message: 'Upload session is not receiving chunks' });
        return;
      }

      if (req.body?.index === undefined || req.body.index < 0 || req.body.index >= session.totalChunks || !req.body.content?.trim()) {
        res.status(400).json({ message: 'valid index and content are required' });
        return;
      }

      const wasFilled = Boolean(session.chunks[req.body.index]);
      session.chunks[req.body.index] = req.body.content;
      session.receivedChunks = session.chunks.filter(Boolean).length;
      session.totalCharacters = session.chunks.reduce((total, chunk) => total + chunk.length, 0);
      session.updatedAt = now();

      if (!wasFilled && session.receivedChunks === session.totalChunks) {
        session.status = 'assembled';
      }

      record.project.updatedAt = now();
      await projectRepository.save(record);

      res.status(200).json(session);
    }
  );

  router.post('/api/upload-sessions/:uploadSessionId/finalize', async (req, res) => {
    const snapshots = await projectRepository.list();
    const projectRecords = await Promise.all(snapshots.map((snapshot) => projectRepository.get(snapshot.project.id)));
    const record = projectRecords.find((item) => item?.uploadSessions.some((session) => session.id === req.params.uploadSessionId));

    if (!record) {
      res.status(404).json({ message: 'Upload session not found' });
      return;
    }

    const session = record.uploadSessions.find((item) => item.id === req.params.uploadSessionId);
    if (!session) {
      res.status(404).json({ message: 'Upload session not found' });
      return;
    }

    if (session.receivedChunks !== session.totalChunks) {
      res.status(400).json({ message: 'all chunks must be uploaded before finalize' });
      return;
    }

    const text = session.chunks.join('\n\n');
    const result = importNovel(record.project.id, {
      title: session.title,
      author: session.author,
      text
    });

    record.novel = result.novel;
    record.characters = result.characters;
    clearGeneratedOutputs(record, { keepAssets: true, keepUploadSessions: true });
    session.status = 'imported';
    session.updatedAt = now();
    record.project.stage = 'novel_imported';
    record.project.updatedAt = now();
    appendVersion(record, {
      stage: record.project.stage,
      action: 'upload_session_completed',
      summary: `分片导入完成《${session.title}》`,
      detail: `共接收 ${session.totalChunks} 片，累计 ${session.totalCharacters} 字符，并已完成小说导入。`,
      metadata: {
        totalChunks: session.totalChunks,
        totalCharacters: session.totalCharacters
      }
    });
    appendVersion(record, {
      stage: record.project.stage,
      action: 'novel_imported',
      summary: `导入小说《${result.novel.title}》`,
      detail: `完成原著导入，共切分 ${result.novel.chapterCount} 章，抽取 ${result.characters.length} 个核心角色。`,
      metadata: {
        chapterCount: result.novel.chapterCount,
        characterCount: result.characters.length,
        wordCount: result.novel.wordCount
      }
    });
    applyBaselineEpisodePackage(record);
    await projectRepository.save(record);

    res.status(201).json(record);
  });

