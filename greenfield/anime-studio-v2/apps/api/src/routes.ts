function now(): string {
  return new Date().toISOString();
}

async function getProjectOr404(projectId: string, res: Response) {
  const record = await projectRepository.get(projectId);
  if (!record) {
    res.status(404).json({ message: 'Project not found' });
    return undefined;
  }
  return record;
}

function applyBaselineEpisodePackage(record: Awaited<ReturnType<typeof projectRepository.get>>) {
  if (!record?.novel) {
    return;
  }

  const episodePackage = buildEpisodePackage(record.project.id, record.novel.title, record.novel.chapters, record.characters, {
    episodeNo: 1,
    adaptationMode: 'faithful',
    estimatedMinutes: 24
  });

  clearEpisodeOutputs(record, episodePackage.outline.episodeNo);
  record.episodeOutlines = record.episodeOutlines.concat(episodePackage.outline);
  record.scenes = record.scenes.concat(episodePackage.scenes);
  record.shots = record.shots.concat(episodePackage.shots);
  record.issues = episodePackage.issues;
  record.project.stage = 'reviewed';
  record.project.updatedAt = now();
  appendVersion(record, {
    stage: record.project.stage,
    action: 'episode_package_generated',
    summary: `生成第 ${episodePackage.outline.episodeNo} 集整包`,
    detail: `导入完成后已自动生成基础剧本产物：${episodePackage.scenes.length} 个分场、${episodePackage.shots.length} 个分镜、${episodePackage.issues.length} 条审查结果。`,
    metadata: {
      episodeNo: episodePackage.outline.episodeNo,
      sceneCount: episodePackage.scenes.length,
      shotCount: episodePackage.shots.length,
      issueCount: episodePackage.issues.length,
      autoGenerated: true
    }
  });
}

function isWeakTitle(title: string | undefined): boolean {
  const normalized = title?.trim() || '';
  return normalized === '' || ['未命名小说', '雨夜真相', '小说正文', '新建小说'].includes(normalized);
}

function isSuspiciousStoredFilename(name: string): boolean {
  const basename = name.replace(/\.[^.]+$/, '');
  return basename.length > 0 && /^[_?]+$/u.test(basename);
}

function recoverStoredFilename(name: string, title: string): string {
  const extension = name.match(/\.[^.]+$/)?.[0] || '.txt';
  return `${title}${extension}`;
}

function deriveTitleFromStoredFilename(name: string): string {
  return name.replace(/\.[^.]+$/, '').replace(/^[_?]+|[_?]+$/g, '').trim();
}

